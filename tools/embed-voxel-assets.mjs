#!/usr/bin/env node
/**
 * Turns the voxel kit's binary art into text.
 *
 * An html-capture pack in this repo holds text files only — that rule is why a pack can be reviewed in a diff and why a
 * worker never serves binaries out of a pack directory. The kit, though, is 57 PNG textures and a pixel typeface. So they
 * are inlined as data URLs into one generated module, `render/assets/blob.js`, which the page resolves textures and fonts
 * through. Same pixels, no binaries in git, and the file is regenerable.
 *
 *   VOXEL_KIT=/opt/data/assets/mc node tools/embed-voxel-assets.mjs
 *
 * Only the textures the block map actually names are embedded (plus the villager the fit uses), so the pack carries the
 * art it draws and nothing else.
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const KIT = process.env.VOXEL_KIT ?? "/opt/data/assets/mc";
const PACK = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..", "packs", "voxel-build");
const OUT = path.join(PACK, "render", "assets", "blob.js");
const FONT = "/opt/data/venstudio-styles/skills/kits/claude-animation-skills/files/fonts/PixelifySans-700-normal.woff2";

const blockmap = JSON.parse(readFileSync(path.join(KIT, "vendor", "blockmap.json"), "utf8"));

/** Every texture path the block map names, in a stable order. */
const wanted = new Set();
for (const spec of Object.values(blockmap)) {
  for (const value of Object.values(spec.tex ?? {})) {
    for (const v of Array.isArray(value) ? value : [value]) if (typeof v === "string") wanted.add(v);
  }
}
// The fit's own art: the villager is loaded by mcrig from the vendor root, not through the block map.
wanted.add("mobs_mc_villager.png");

const textures = {};
let bytes = 0;
for (const rel of [...wanted].sort()) {
  let file = path.join(KIT, "vendor", rel);
  try {
    readFileSync(file);
  } catch {
    // The kit keeps the block-map paths under vendor/ already; a bare name falls back to the vendor root.
    file = path.join(KIT, "vendor", path.basename(rel));
  }
  const buf = readFileSync(file);
  bytes += buf.length;
  textures[rel] = `data:image/png;base64,${buf.toString("base64")}`;
}

const fontBuf = readFileSync(FONT);
bytes += fontBuf.length;

const body = `/* GENERATED by tools/embed-voxel-assets.mjs — do not edit by hand.
 *
 * ${Object.keys(textures).length} block textures (${(bytes / 1024).toFixed(0)} KB decoded) from the Pixel-Perfection kit, CC BY-SA 4.0,
 * and the Pixelify Sans typeface, SIL OFL 1.1, as data URLs. Regenerate from the kit and review the diff; the pack's
 * provenance records both licences.
 */
export const textures = ${JSON.stringify(textures, null, 0)};

export const font = "data:font/woff2;base64,${fontBuf.toString("base64")}";
`;
writeFileSync(OUT, body);
console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${Object.keys(textures).length} textures, ${(body.length / 1024).toFixed(0)} KB of text`);