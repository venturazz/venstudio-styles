#!/usr/bin/env node
/**
 * Inlines the Roblox kit's face atlases as data URLs, in chunks small enough for the repo's 1 MB file rule.
 *
 * An html-capture pack holds text only. The kit draws faces from 14 PNG atlases (eyes and mouth per face style); they travel
 * as base64 in a few modules the page merges at load. Lossless on purpose: a downscaled face is a different face.
 *
 *   KIT=/opt/data/robloxkit/engine node tools/embed-blocky-assets.mjs
 */

import { readFileSync, readdirSync, rmSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const KIT = process.env.KIT ?? "/opt/data/robloxkit/engine";
const OUT = path.join(ROOT, "packs", "blocky-story", "render", "assets");
const LIMIT = 700 * 1024; // chars per module, well under the validator's 1 MB file cap

const files = readdirSync(path.join(KIT, "assets", "faces")).filter((f) => f.endsWith(".png")).sort();
if (files.length === 0) throw new Error(`no face atlases in ${KIT}/assets/faces`);

const entries = files.map((f) => {
  const buf = readFileSync(path.join(KIT, "assets", "faces", f));
  return [`faces/${f}`, `data:image/png;base64,${buf.toString("base64")}`];
});

rmSync(path.join(OUT, "faces-0.js"), { force: true });
for (const stale of readdirSync(OUT).filter((f) => /^faces-\d+\.js$/.test(f))) rmSync(path.join(OUT, stale));

const chunks = [];
let current = {};
let size = 0;
for (const [key, value] of entries) {
  if (size + value.length > LIMIT && Object.keys(current).length > 0) {
    chunks.push(current);
    current = {};
    size = 0;
  }
  current[key] = value;
  size += value.length;
}
if (Object.keys(current).length > 0) chunks.push(current);

mkdirSync(OUT, { recursive: true });
chunks.forEach((chunk, i) => {
  const body = `/* GENERATED by tools/embed-blocky-assets.mjs — face atlases from the Roblox kit, part ${i + 1} of ${chunks.length}.
 * Loaded as a classic script before page.js: a pack page is a plain <script src>, so this registers itself instead of
 * exporting, and the bundle stays under the repo's 1 MB per-file rule without the atlases inside it. */
window.__BLOCKY_ATLASES = Object.assign(window.__BLOCKY_ATLASES || {}, ${JSON.stringify(chunk)});\n`;
  writeFileSync(path.join(OUT, `faces-${i}.js`), body);
});
console.log(`wrote ${chunks.length} module(s): ${entries.length} face atlases, ${(size / 1024).toFixed(0)} KB of text`);